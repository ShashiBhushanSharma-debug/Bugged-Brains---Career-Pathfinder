class DynamicRationale(BaseModel):
    why_now: str = Field(description="Clear reason why this node is placed at this point in the path.")
    skill_gap_addressed: str = Field(description="The specific skill gap or prerequisite targeted.")

class DynamicRoadmapStep(BaseModel):
    node_id: str = Field(description="Unique ID for the step, e.g., 'rm_react_hooks' or 'remedial_state_mgmt'")
    title: str = Field(description="Display title of the learning node.")
    type: str = Field(description="Node type: 'skill', 'course', 'project', or 'assessment'")
    target_skill_id: str = Field(description="Associated skill slug from database catalog.")
    difficulty: str = Field(description="Beginner, Intermediate, or Advanced")
    estimated_hours: int = Field(description="Estimated hours to complete.")
    action_type: str = Field(description="'retained', 'injected_remedial', 'fast_tracked_skip', or 'added'")
    rationale: DynamicRationale

class StructuredReplanOutput(BaseModel):
    headline: str = Field(description="Short summary message for the UI (e.g., 'Path updated to reinforce State Management').")
    reasoning: str = Field(description="Detailed narrative explaining how the path adapted to user performance.")
    updated_steps: List[DynamicRoadmapStep]

class AdaptiveGraphState(TypedDict):
    pool: asyncpg.Pool
    learner_id: str
    target_career_id: str
    assessment_signal: Dict[str, Any]  # {step_id, target_skill_id, score_percentage, user_feedback}
    current_skills: Dict[str, float]   # {skill_id: proficiency_score (0.0 - 1.0)}
    career_requirements: Dict[str, int] # {skill_id: required_score (0 - 100)}
    skill_gaps: List[Dict[str, Any]]
    current_roadmap_nodes: List[Dict[str, Any]]
    
    # Outputs generated by workflow
    new_mastery_score: Optional[float]
    replan_output: Optional[Dict[str, Any]]
    replan_status_message: str

